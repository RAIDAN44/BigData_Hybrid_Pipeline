"""
settings.py
-----------

وظيفة الملف:
هذا الملف يحتوي على الإعدادات المركزية للمشروع.

بدل أن نكتب المسارات، وأسماء قواعد البيانات، وأسماء الـ Collections،
وإعدادات Spark، وحجم الـ Batch في أكثر من ملف داخل المشروع،
نقوم بتجميعها هنا في مكان واحد.

الملف لا يقوم بمعالجة البيانات بنفسه، وإنما يوفر الإعدادات
والثوابت لبقية ملفات المشروع حتى تستخدمها أثناء التنفيذ.

أهم ما يحتويه:
1. مسارات مجلدات المشروع.
2. إعدادات الاتصال بـ MongoDB.
3. أسماء MongoDB Collections.
4. الحد الذي يحدد هل الملف صغير أم كبير.
5. حجم الدفعات المستخدمة في Python Batch.
6. إعدادات Apache Spark.
7. ثوابت موحدة لأسماء محركات المعالجة وحالات جودة البيانات.
"""

# Path تستخدم لبناء مسارات الملفات والمجلدات بطريقة منظمة
from pathlib import Path

# os نستخدمها هنا لقراءة Environment Variables
import os


# ============================================================
# PROJECT PATHS
# مسارات المشروع
# ============================================================

# تحديد المجلد الرئيسي للمشروع.
# __file__ يمثل ملف settings.py الحالي.
# resolve() يحصل على المسار الكامل للملف.
# parent الأولى تنتقل إلى مجلد config.
# parent الثانية تنتقل إلى المجلد الرئيسي BigData_Hybrid_Pipeline.
PROJECT_ROOT = Path(__file__).resolve().parent.parent


# مجلد البيانات الرئيسي داخل المشروع.
DATA_DIR = PROJECT_ROOT / "data"

# المجلد الذي يحتوي على ملفات البيانات التي سيدخلها المستخدم للنظام.
INPUT_DIR = DATA_DIR / "input"

# مجلد يحتوي على عينات بيانات صغيرة للاختبار أو العرض.
SAMPLES_DIR = DATA_DIR / "samples"


# مجلد التقارير والنتائج الناتجة عن تشغيل المشروع.
REPORTS_DIR = PROJECT_ROOT / "reports"

# المسار الكامل لملف JSON الذي يتم فيه حفظ نتائج التنفيذ.
RESULTS_JSON_PATH = REPORTS_DIR / "results.json"

# المجلد المخصص لحفظ Screenshots أو أدلة التنفيذ.
SCREENSHOTS_DIR = REPORTS_DIR / "screenshots"


# ============================================================
# MONGODB
# إعدادات قاعدة البيانات MongoDB
# ============================================================

# عنوان الاتصال بخادم MongoDB.
#
# os.getenv يحاول أولاً قراءة Environment Variable باسم MONGO_URI.
# إذا لم يكن موجوداً، يستخدم القيمة الافتراضية:
# mongodb://127.0.0.1:27017
#
# 127.0.0.1 تعني أن MongoDB تعمل على نفس الجهاز Localhost.
# 27017 هو منفذ MongoDB الافتراضي.
MONGO_URI = os.getenv(
    "MONGO_URI",
    "mongodb://127.0.0.1:27017"
)


# اسم قاعدة البيانات التي يستخدمها المشروع.
#
# يمكن تغيير الاسم من Environment Variable بدون تعديل الكود.
# إذا لم توجد قيمة خارجية، يستخدم المشروع bigdata_midterm.
MONGO_DATABASE = os.getenv(
    "MONGO_DATABASE",
    "bigdata_midterm"
)


# Collection لحفظ البيانات الخام قبل انتهاء عملية التحقق والتنظيف.
RAW_COLLECTION = "orders_raw"

# Collection لحفظ السجلات التي تم التحقق منها وأصبحت صالحة للاستخدام.
VALIDATED_COLLECTION = "orders_validated"

# Collection لعزل السجلات التي تحتوي على أخطاء
# أو مشاكل تمنع اعتمادها ضمن البيانات الصحيحة.
QUARANTINE_COLLECTION = "orders_quarantine"


# ============================================================
# FILE ROUTER
# إعدادات اختيار محرك المعالجة
# ============================================================

# الحد الفاصل بين الملف الصغير والملف الكبير بالميجابايت.
#
# القيمة الافتراضية هي 200 MB.
#
# File Router يستخدم هذه القيمة ليقرر أي محرك معالجة مناسب:
# - الملفات الصغيرة  -> Python Batch
# - الملفات الكبيرة -> PySpark
#
# os.getenv يعيد القيمة كنص String،
# لذلك نستخدم int لتحويلها إلى رقم صحيح Integer.
SMALL_FILE_THRESHOLD_MB = int(
    os.getenv("SMALL_FILE_THRESHOLD_MB", "200")
)


# ============================================================
# PYTHON BATCH
# إعدادات المعالجة باستخدام Python
# ============================================================

# عدد السجلات التي تتم معالجتها في كل دفعة Batch.
#
# القيمة الافتراضية هي 5000 سجل.
#
# معالجة البيانات على دفعات تساعد في عدم تحميل
# كمية كبيرة جداً من البيانات إلى الذاكرة دفعة واحدة.
BATCH_SIZE = int(
    os.getenv("BATCH_SIZE", "5000")
)


# ============================================================
# SPARK
# إعدادات Apache Spark
# ============================================================

# اسم تطبيق Spark الذي سيظهر عند إنشاء SparkSession.
SPARK_APP_NAME = "BigDataHybridPipeline"


# تحديد مكان وطريقة تشغيل Spark.
#
# local[*] تعني:
# تشغيل Spark محلياً على نفس الجهاز،
# واستخدام جميع أنوية CPU المتاحة.
#
# يمكن تغيير هذه القيمة باستخدام Environment Variable
# إذا أردنا تشغيل المشروع في بيئة Spark مختلفة.
SPARK_MASTER = os.getenv(
    "SPARK_MASTER",
    "local[*]"
)


# اسم Data Source Format المستخدم عند ربط Spark مع MongoDB
# من خلال MongoDB Spark Connector.
MONGO_SPARK_FORMAT = "mongodb"


# ============================================================
# PROJECT CONSTANTS
# الثوابت العامة للمشروع
# ============================================================

# أسماء محركات المعالجة.
#
# نستخدم Constants بدلاً من كتابة النصوص نفسها
# في أكثر من ملف لتقليل الأخطاء وتوحيد القيم.
ENGINE_PYTHON_BATCH = "python_batch"
ENGINE_PYSPARK = "pyspark"


# حالات جودة البيانات بعد عملية التحقق والتنظيف.

# السجل صحيح ولم يحتج إلى تعديل.
QUALITY_VALID = "valid"

# السجل كان يحتوي على مشكلة،
# لكن النظام استطاع تصحيحها وأصبح صالحاً.
QUALITY_CORRECTED = "corrected"

# السجل يحتوي على مشكلة تمنع اعتماده،
# ولذلك يتم عزله في Quarantine.
QUALITY_QUARANTINED = "quarantined"